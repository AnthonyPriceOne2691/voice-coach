#!/usr/bin/env python3
"""Что проект ЗАЯВИЛ о каноне: версии в шапках и записи `stack:`.

Часть доктора (вход — `contour_doctor.py`). Отделено от `doctor_layout.py` в
`cqg@2.02`: тот дошёл до 406 строк при планке 300 (§9.1a п.5). Граница выбрана
проверяемая, а не по вкусу — здесь НЕ читаются ни хуки, ни инструменты, ни тела
конфигов: только заявления о версии и их согласие между собой.
"""

from __future__ import annotations

import re
from pathlib import Path

from doctor_core import ABSENT, AUTO, WEAK

CANONS = ("AGENT_STACK.md", "AGENT_DELIVERY_HARNESS.md",
          "CODE_QUALITY_GATES.md", "OKF_KNOWLEDGE_BUNDLE.md")


class VersionChecks:
    # --- A. каноны -----------------------------------------------------------
    #: Где канон САМ предписывает записать версию стека: три места, три разные
    #: метки. Список не придуман здесь — он вынут из шаблонов A.2/A.1/A.12, и
    #: оракул сьюта выводит его ОТТУДА же: появится четвёртая запись — тест
    #: покраснеет, а не промолчит.
    #:
    #: ⚠ Читалась ОДНА из трёх (`cqg@1.78` завёл сверку снимка со STATUS и на этом
    #: остановился), то есть у версии было три источника правды при одном
    #: проверяющем — «второй список, который никто не сверяет» (тот же класс, из-за
    #: которого §9.1a держит счётчик гейтов в одном месте, а из README убраны
    #: версии, `cqg@1.59`). Замер на живом развёртывании 2026-08-11: STATUS
    #: `cqg@1.61`, CONSTITUTION и STACK-ACCEPTANCE обе `cqg@1.7` — две записи из
    #: трёх врали 40 ревизий, и предыдущее обновление поправило ровно ту, которую
    #: спрашивает механика.
    #:
    #: ⚠ Признак — МЕТКА строки, а не токен `слой@версия`, и обоснование тут
    #: узкое нарочно. Обход по всему дереву на токенах даёт 52 ложных
    #: срабатывания (замер 2026-08-11) — но пути здесь фиксированы, поэтому цена
    #: другая: в САМИХ этих файлах проза про версии лежит рядом с записью. У
    #: STATUS есть шапка, а обновление принято описывать словами («переходим с
    #: … на …»), и проза выше записи читается за неё. Первая проба на это
    #: промахнулась (положила абзац НИЖЕ, обход до него не дошёл) и «прошла» на
    #: наивной форме — прогон, который ничего не сломал, ничего и не доказывает.
    STACK_RECORDS = (
        ("delivery/active/STATUS.md", r"^\s*-\s*\*\*stack:\*\*"),
        ("delivery/CONSTITUTION.md", r"^\*\*Canon stack:\*\*"),
        ("delivery/STACK-ACCEPTANCE.md", r"^\*\*Stack:\*\*"),
    )

    def _records(self, prefix: str) -> list[tuple[str, str]]:
        """Все записи проекта о версии слоя: `[(файл, версия), …]`.

        `absent` — законное значение (`okf@absent` на проекте без канона смысла),
        поэтому оно ЧИТАЕТСЯ: три записи с `absent` согласны, а `absent` против
        числа — настоящее расхождение. В `_declared_version` оно, наоборот, не
        годится, и почему — сказано там.
        """
        out: list[tuple[str, str]] = []
        if not prefix:
            return out
        for rel, label in self.STACK_RECORDS:
            p = self.root / rel
            if not p.is_file():
                continue
            for line in p.read_text("utf-8", errors="replace").splitlines():
                if not re.match(label, line):
                    continue
                m = re.search(rf"\b({re.escape(prefix)}@(?:[0-9][0-9.]*|absent))", line)
                if m:
                    out.append((rel, m.group(1)))
                break
        return out

    def _declared_version(self, prefix: str) -> str:
        """Версия слоя из строки `stack:` в STATUS — то, что проект ЗАЯВИЛ.

        Заявление и снимок обязаны совпадать: расходятся — одно из двух врёт, и
        какое именно, отсюда не видно, но молчать нельзя.

        ⚠ `absent` здесь отбрасывается, и это не мелочь: потребитель — сверка
        «снимок отстал от payload», а снимок варианта C несёт ВСЕ четыре канона
        даже когда проект развернул три. Прими `okf@absent` за заявление — и
        доктор объявит отставшим снимок, который в порядке, то есть даст ложное
        срабатывание на штатной раскладке.
        """
        for rel, v in self._records(prefix):
            if rel.endswith("STATUS.md"):
                return "" if v.endswith("@absent") else v
        return ""

    def check_stack_records(self) -> None:
        """Записи о версии стека обязаны СОГЛАСОВАТЬСЯ между собой.

        Вопрос отдельный от «снимок против payload»: тот сверяет проект с
        каноном, этот — проект сам с собой. Расхождение здесь значит, что одна из
        записей врёт, и какая — видно по адресам, поэтому они печатаются все.

        Вердикт `WEAK`, как у сверки снимка: быть посреди обновления законно, и
        `DEAD` уронил бы прогон ровно там, где обновление идёт правильно
        (§4.3b — красное всегда снимают первым). Молчать нельзя, ронять нечестно.
        """
        for prefix in ("delivery", "cqg", "okf"):
            recs = self._records(prefix)
            point = f"записи о версии {prefix}"
            if len(recs) < 2:
                continue                 # одна запись или ни одной — сверять нечего
            seen = {v for _, v in recs}
            if len(seen) == 1:
                self.add(AUTO, point, f"{recs[0][1]} — {len(recs)} записи согласны")
                continue
            self.add(WEAK, point,
                     "расходятся: "
                     + ", ".join(f"{rel} → {v}" for rel, v in recs)
                     + " — одна из них врёт; обновление правит ВСЕ записи (§5.5)")

    def _canon_version(self, p: Path) -> str:
        """Версия из шапки канона; пусто — шапка не читается.

        Шов по данным: наружу шло одно значение — строка версии, а не сам
        match. Заодно файл читается ОДИН раз: обе формы шапки (`Canon version:`
        у канонов, `Эта карта:` у карты стека) брали текст заново.
        """
        text = p.read_text("utf-8")
        m = (re.search(r"\*\*Canon version:\*\*\s*`([^`]+)`", text)
             or re.search(r"\*\*Эта карта:\*\*\s*`([^`]+)`", text))
        return m.group(1) if m else ""

    def _version_drift(self, current: str) -> str:
        """Отстал ли СНИМОК канона от того, что проект ЗАЯВИЛ в STATUS.

        Шов по данным: наружу блок отдавал одно имя — `drift`, строку-хвост
        сообщения; `declared` живёт только здесь. Пустая строка вместо флага —
        чтобы вызывающий не пересобирал текст из двух кусков.

        Снимок сверяется с ЗАЯВЛЕННОЙ версией из STATUS. Иначе он —
        единственный источник правды о самом себе: доктор читал шапку снимка и
        считал её истиной, а проект тем временем развернул более новый payload.
        Замер на живом проекте: скрипты 1.77, снимок 1.75, STATUS 1.77 — и никто
        не сказал ни слова.

        Это делает честным и диагноз расхождения скриптов: без такой проверки
        совет «обнови скрипт из payload'а» вреден, когда на самом деле отстал
        снимок, а не скрипт.
        """
        declared = self._declared_version(current.split("@")[0] if current else "")
        if not current or not declared or declared == current:
            return ""
        return (f" — STATUS заявляет {declared}: снимок ОТСТАЛ от "
                "развёрнутого payload, обнови docs/canon (§5 шаг 11)")

    def check_canons(self) -> None:
        # Каноны лежат ЛИБО в корне, ЛИБО в снимке `docs/canon/` — и второе не
        # экзотика, а дефолт: §5 шаг 11 велит агенту выбирать вариант C, не
        # спрашивая. Первая редакция смотрела только в корень и на правильно
        # развёрнутом проекте печатала «файла нет — слой не развёрнут» по всем
        # четырём. ABSENT не роняет прогон, поэтому ошибка тихая: доктор говорил
        # «бедность» там, где всё на месте, и приёмка §6 читалась бы по нему.
        for name in CANONS:
            p = self.root / name
            if not p.is_file():
                p = self.root / "docs" / "canon" / name
            if not p.is_file():
                self.add(ABSENT, f"канон {name}", "файла нет — слой не развёрнут")
                continue
            version = self._canon_version(p)
            where = "" if p.parent == self.root else f" ({p.parent.relative_to(self.root)})"
            drift = self._version_drift(version)
            self.add(AUTO if (version and not drift) else WEAK, f"канон {name}",
                     (f"версия {version}" if version else "версия в шапке не читается")
                     + where + drift)
